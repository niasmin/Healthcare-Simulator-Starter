export const DICTS: Record<Lang, Dict> = { th, en };

/** Params whose values are themselves i18n keys (e.g. room type ids) are translated too. */
const PARAM_PREFIX: Record<string, string> = { room: 'room.', equipment: 'equip.', role: 'role.', slot: 'slot.', task: 'task.', decor: 'decor.', course: 'course.', upgrade: 'shop.', place: 'city.place.', mission: 'mission.', achievement: 'ach.', prefab: 'prefab.', price: 'fin.price.' };

export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  const dict = DICTS[lang];
  let out = dict[key] ?? DICTS.th[key] ?? key;
  if (params) {
    // People carry both scripts: {name} uses the romanised form in English.
    if (lang === 'en' && params.nameEn !== undefined) params = { ...params, name: params.nameEn };
    if (lang === 'en' && params.orgEn !== undefined) params = { ...params, org: params.orgEn };
    for (const [k, v] of Object.entries(params)) {
      const prefix = PARAM_PREFIX[k];
      const value = prefix && typeof v === 'string' ? (dict[prefix + v] ?? String(v)) : String(v);
      out = out.split(`{${k}}`).join(value);
    }
  }
  return out;
}

export function localeOf(lang: Lang): string {
  return lang === 'th' ? 'th-TH' : 'en-US';
}
